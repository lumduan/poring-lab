"""The hunt block's RULE VERSIONS as the editor shows them (docs/planning/blocks-from-hunt-flow.md
B2; ADR-0020 Amendment A 1 + 3, DRAFT): its groups, each a list of the rule versions a person may
pick, with their numbers (read-only) and their BADGES.

Pure: the caller reads two committed files and hands them over (the backend reads them under
/lab-config, tests from the repo):
- ``config/flows/hunt/index.yaml``: GENERATED by scripts/params_export.py from hunt_flow's PARAMS
  -- the adopted version, each version's rule versions, each rule version's numbers;
- ``config/flows/hunt/evidence.yaml``: HAND-WRITTEN, one row per pre-registered hunt verdict
  (its docs/demonstrations.md entry, the version, map, path, run-hours, hard bars).

THE BADGES (nothing here is a judgement; each badge is derived from those files):
- ``adopted``: the rule version is the adopted base's (index ``adopted``) for that parameter.
- ``versions``: the PARAMS versions whose config carries it (a record, not a claim that they ran).
- ``evidence``: the verdicts of versions whose config carries it that meet Batt's D8 rule
  (2026-10-21, "D8 yes": "a pre-registered hunt verdict with the hard bars at 0 over >= 4 h" gives
  the hunt block a "one path (RDP), <map>" badge). The block's own ``evidence`` badge is the
  paths and maps of every such verdict. It sits BESIDE the L1 verification badge, never in place
  of it: L1's ``verified_on`` is an alone-test, this is hunting evidence (one path, one map, an
  immune GM).

The choices themselves are the registry's (blocks.yaml): a rule version is offered only there; the
index only describes it. A choice the index does not know is shown with ``known`` false (the
linter and the engine refuse nothing more or less because of it).

OPTION parameters (blocks.yaml ``options``; Batt 2026-10-22, the hunt block's ``engage_source``:
``detector`` or ``melee_ring``) sit in their group beside the rule versions, with ``kind``
"option": plain values, no PARAMS version, no numbers and no D8 evidence (the index never holds
them), the registry's ``default`` (what an absent parameter means) and its ``note``. Every
parameter carries ``kind`` ("rule" | "option") and ``required``: the editor writes an optional
parameter only when it differs from its default.
"""

from __future__ import annotations

from collections.abc import Mapping
from typing import Any

from poring_flow.catalogue import Catalogue, catalogue

HUNT = "hunt"
INDEX_KIND = "hunt-config-index"
EVIDENCE_KIND = "hunt-evidence"
# Batt D8 (2026-10-21): a pre-registered verdict, hard bars 0, at least 4 run-hours
D8_MIN_HOURS = 4.0
# the "stop" group: no parameter; the enclosing loop's condition and max_s (13.5; plan 2a)
STOP_NOTE = "the enclosing loop: its condition (e.g. weight_percent()) and max_s (13.5)"


class RulesError(ValueError):
    """An index or evidence document that is not what this module reads (fail closed: no badge)."""


def _map(x: Any, where: str) -> Mapping[str, Any]:
    if not isinstance(x, Mapping):
        raise RulesError(f"{where}: not a mapping")
    return x


def d8_ok(row: Mapping[str, Any]) -> tuple[bool, str]:
    """Does an evidence row meet D8's rule? (ok, why not)."""
    bars = row.get("hard_bars")
    hours = float(row.get("runs", 0)) * float(row.get("minutes", 0)) / 60.0
    if not row.get("pre_registered"):
        return False, "not pre-registered"
    if not isinstance(bars, list) or len(bars) != 3 or any(b != 0 for b in bars):
        return False, f"hard bars {bars}"
    if hours < D8_MIN_HOURS:
        return False, f"{hours:g} run-hours (D8: at least {D8_MIN_HOURS:g})"
    return True, ""


def _evidence_rows(evidence: Mapping[str, Any] | None) -> list[dict[str, Any]]:
    if evidence is None:
        return []
    ev = _map(evidence, "evidence")
    if ev.get("kind") != EVIDENCE_KIND or ev.get("format") != 1:
        raise RulesError(f"evidence: kind {ev.get('kind')!r} format {ev.get('format')!r}")
    rows = ev.get("verdicts")
    if not isinstance(rows, list):
        raise RulesError("evidence: verdicts is a list")
    out = []
    for i, r in enumerate(rows):
        r = _map(r, f"evidence.verdicts[{i}]")
        need = {"entry", "version", "map", "path", "runs", "minutes", "hard_bars",
                "pre_registered", "verdict", "gm"}  # fmt: skip
        if set(r) != need:
            raise RulesError(f"evidence.verdicts[{i}]: keys {sorted(r)}; a row has {sorted(need)}")
        ok, why = d8_ok(r)
        hours = float(r["runs"]) * float(r["minutes"]) / 60.0
        out.append({
            "entry": str(r["entry"]), "version": int(r["version"]), "map": str(r["map"]),
            "path": str(r["path"]), "hours": hours, "hard_bars": list(r["hard_bars"]),
            "verdict": str(r["verdict"]), "gm": str(r["gm"]), "d8": ok, "why_not": why,
        })  # fmt: skip
    return out


def rules_doc(
    index: Mapping[str, Any],
    evidence: Mapping[str, Any] | None = None,
    cat: Catalogue | None = None,
) -> dict[str, Any]:
    """The editor's hunt-block document: groups -> parameters -> rule versions with badges."""
    cat = catalogue() if cat is None else cat
    blk = cat.blocks.get(HUNT)
    if blk is None:
        raise RulesError("the registry has no hunt block")
    idx = _map(index, "index")
    if idx.get("kind") != INDEX_KIND or idx.get("format") != 1:
        raise RulesError(f"index: kind {idx.get('kind')!r} format {idx.get('format')!r}")
    raw_versions = _map(idx["versions"], "index.versions")
    versions = {int(k): _map(v, f"index.versions.{k}") for k, v in raw_versions.items()}
    rules = _map(idx["rules"], "index.rules")
    adopted = int(idx["adopted"])
    if adopted not in versions:
        raise RulesError(f"index: the adopted version {adopted} is not in versions")
    rows = _evidence_rows(evidence)
    for r in rows:
        if r["version"] not in versions:
            raise RulesError(f"evidence {r['entry']}: version {r['version']} is not in the index")
    groups: list[dict[str, Any]] = []
    by_group: dict[str, dict[str, Any]] = {}
    for p in blk.spec.params:
        if not (p.choices or p.options):
            continue
        g = p.group or p.name
        if g not in by_group:
            by_group[g] = {"name": g, "params": []}
            groups.append(by_group[g])
        if p.options:
            dflt = p.default if p.default is not None else p.options[0]
            by_group[g]["params"].append({
                "name": p.name, "kind": "option", "required": p.required, "default": dflt,
                "note": p.note or "",
                "choices": [
                    {"id": o, "known": True, "values": {}, "versions": [], "adopted": False,
                     "evidence": [], "option": True, "is_default": o == dflt}
                    for o in p.options
                ],
            })  # fmt: skip
            continue
        known_rules = _map(rules.get(p.name, {}), f"index.rules.{p.name}")
        choices = []
        for c in p.choices:
            vs = sorted(v for v, row in versions.items() if row.get(p.name) == c)
            ev = [
                {k: r[k] for k in ("entry", "version", "map", "path", "hours", "verdict", "gm")}
                for r in rows
                if r["d8"] and versions[r["version"]].get(p.name) == c
            ]
            values = known_rules.get(c)
            choices.append({
                "id": c, "known": values is not None, "values": dict(values or {}),
                "versions": vs, "adopted": versions[adopted].get(p.name) == c, "evidence": ev,
            })  # fmt: skip
        adopted_choice = versions[adopted].get(p.name)
        by_group[g]["params"].append({
            "name": p.name, "kind": "rule", "required": p.required, "choices": choices,
            "default": adopted_choice if adopted_choice in p.choices else p.choices[0],
        })  # fmt: skip
    groups.append({"name": "stop", "params": [], "note": STOP_NOTE})
    d8 = [r for r in rows if r["d8"]]
    badge = sorted({f"one path ({r['path'].upper()}), {r['map']}" for r in d8})
    return {
        "block": HUNT,
        "adopted": adopted,
        "groups": groups,
        "evidence": {
            "badges": badge,
            "rule": (
                "D8 (Batt 2026-10-21): a pre-registered hunt verdict, hard bars 0 / 0 / 0, "
                f">= {D8_MIN_HOURS:g} run-hours"
            ),
            "verdicts": rows,
        },
    }
