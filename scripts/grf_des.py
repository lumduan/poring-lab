HEADER_BLOCKS = 20


def permute(value: int, table: tuple[int, ...], width: int) -> int:
    """FIPS bit numbering: bit 1 is the most significant of the ``width``-bit input."""
    out = 0
    for pos in table:
        out = (out << 1) | ((value >> (width - pos)) & 1)
    return out


def feistel(right: int, subkey: int) -> int:
    """f(R, K) = P(S(E(R) xor K)), 32 bits."""
    x = permute(right, E, 32) ^ subkey
    out = 0
    for i in range(8):
        six = (x >> (42 - 6 * i)) & 0x3F
        row, col = ((six & 0x20) >> 4) | (six & 1), (six >> 1) & 0xF
        out = (out << 4) | S[i][row * 16 + col]
    return permute(out, P, 32)


def grf_block(block: bytes) -> bytes:
    """IP, one round with a zero subkey (left ^= f(right), no swap), FP. Its own inverse."""
    x = permute(int.from_bytes(block, "big"), IP, 64)
    left, right = x >> 32, x & 0xFFFFFFFF
    left ^= feistel(right, 0)
    return permute((left << 32) | right, FP, 64).to_bytes(8, "big")


def decode_header(data: bytes) -> bytes:
    """An entry with flag 0x04: the first 20 blocks pass through grf_block; the rest is plain."""
    n = min(HEADER_BLOCKS, len(data) // 8)
    head = b"".join(grf_block(data[8 * i : 8 * i + 8]) for i in range(n))
    return head + data[8 * n :]
