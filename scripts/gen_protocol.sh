#!/usr/bin/env bash
# Regenerate the wire-protocol artifacts from the Pydantic models (the single source of truth):
#   packages/poring_env/schema/protocol.schema.json   (pytest fails when this is stale)
#   services/frontend/src/lib/protocol.gen.ts         (json-schema-to-typescript)
#   services/frontend/src/lib/keycodes.gen.ts         (codes the backend keymap can inject)
#   packages/poring_packets/schema/packets.schema.json + services/frontend/src/lib/packets.gen.ts
#     (ADR-0007 packet events: a SEPARATE schema -- never part of poring_env's protocol)
#   packages/poring_flow/schema/flow.schema.json + services/frontend/src/lib/flow/flow.gen.ts
#     (ADR-0020 flow IR, MW2's editor; the schema is drift-tested by poring_flow's test_schema.py)
#   packages/poring_flow/schema/project.schema.json + services/frontend/src/lib/flow/project.gen.ts
#     (the PROJECT model, format 3: what /maps and /flows edit; drift-tested by test_project.py)
#   services/frontend/src/lib/flow/settings.gen.ts (the setting blocks' registry, poring_flow.settings;
#     drift-tested by packages/poring_flow/tests/test_settings.py)
# Run after ANY change to poring_env/protocol.py or poring_packets/events.py; commit all of them.
set -euo pipefail
cd "$(dirname "$0")/.."

uv run poring-protocol-schema >packages/poring_env/schema/protocol.schema.json
uv run poring-packets-schema >packages/poring_packets/schema/packets.schema.json
uv run poring-flow-schema >packages/poring_flow/schema/flow.schema.json
uv run python -m poring_flow.project >packages/poring_flow/schema/project.schema.json
uv run python -c 'from poring_env.keymap import typescript_module; print(typescript_module(), end="")' \
  >services/frontend/src/lib/keycodes.gen.ts
# the SETTING BLOCKS' registry (docs/planning/live-blocks.md 12; drift-tested by test_settings.py)
uv run python -c 'from poring_flow import functions, settings
print(settings.typescript_module(functions.RUNNER_MAPS), end="")' \
  >services/frontend/src/lib/flow/settings.gen.ts
BANNER='/* GENERATED by scripts/gen_protocol.sh from packages/poring_env/schema/protocol.schema.json (Pydantic models in poring_env.protocol). DO NOT EDIT. */'
PACKETS_BANNER='/* GENERATED by scripts/gen_protocol.sh from packages/poring_packets/schema/packets.schema.json (Pydantic models in poring_packets.events, ADR-0007). DO NOT EDIT. */'
FLOW_BANNER='/* GENERATED by scripts/gen_protocol.sh from packages/poring_flow/schema/flow.schema.json (Pydantic models in poring_flow.ir, ADR-0020). DO NOT EDIT. */'
PROJECT_BANNER='/* GENERATED by scripts/gen_protocol.sh from packages/poring_flow/schema/project.schema.json (Pydantic models in poring_flow.project, the project model: format 3). DO NOT EDIT. */'
if [[ -d services/frontend/node_modules ]]; then
  # corepack resolves the pnpm version from the package.json in the CURRENT directory.
  (cd services/frontend && COREPACK_ENABLE_DOWNLOAD_PROMPT=0 corepack pnpm run -s gen:protocol)
  (cd services/frontend && COREPACK_ENABLE_DOWNLOAD_PROMPT=0 corepack pnpm run -s gen:packets)
  (cd services/frontend && COREPACK_ENABLE_DOWNLOAD_PROMPT=0 corepack pnpm run -s gen:flow)
  (cd services/frontend && COREPACK_ENABLE_DOWNLOAD_PROMPT=0 corepack pnpm exec json2ts \
    --unreachableDefinitions --ignoreMinAndMaxItems --bannerComment "${PROJECT_BANNER}" \
    <../../packages/poring_flow/schema/project.schema.json >src/lib/flow/project.gen.ts.new &&
    mv src/lib/flow/project.gen.ts.new src/lib/flow/project.gen.ts)
elif docker ps --format '{{.Names}}' | grep -qx poring-lab-frontend-dev-1; then
  # This host keeps node_modules OFF the disk it shares with live capture: run json2ts inside
  # frontend-dev (node_modules on tmpfs) over stdin/stdout.
  # Same flags as package.json's gen:protocol / gen:packets / gen:flow, byte-identical output.
  json2ts() { # <schema> <out> <banner> [extra flag]
    docker exec -i -w /app poring-lab-frontend-dev-1 corepack pnpm exec json2ts \
      --unreachableDefinitions ${4:-} --bannerComment "$3" <"$1" >"$2.new"
    mv "$2.new" "$2"
  }
  json2ts packages/poring_env/schema/protocol.schema.json \
    services/frontend/src/lib/protocol.gen.ts "${BANNER}"
  json2ts packages/poring_packets/schema/packets.schema.json \
    services/frontend/src/lib/packets.gen.ts "${PACKETS_BANNER}"
  json2ts packages/poring_flow/schema/flow.schema.json \
    services/frontend/src/lib/flow/flow.gen.ts "${FLOW_BANNER}" --ignoreMinAndMaxItems
  json2ts packages/poring_flow/schema/project.schema.json \
    services/frontend/src/lib/flow/project.gen.ts "${PROJECT_BANNER}" --ignoreMinAndMaxItems
else
  echo "gen_protocol: no services/frontend/node_modules and frontend-dev is not running." >&2
  echo "Start it (scripts/dev.sh up -d frontend-dev); do NOT pnpm install on this host." >&2
  exit 1
fi
git status --short -- packages/poring_env/schema packages/poring_packets/schema \
  packages/poring_flow/schema services/frontend/src/lib/ 2>/dev/null || true
