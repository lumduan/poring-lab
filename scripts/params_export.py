#!/usr/bin/env python3
"""Export hunt_flow's PARAMS as hunt-block configs (docs/planning/blocks-from-hunt-flow.md, B1;
the format and the key classes: scripts/hunt_config.py).

    params_export.py classify [--version N]   every key's class and hunt parameter (default: all
                                              versions' keys); keys newer than the reviewed table
                                              are flagged REVIEW; exit 1 on an unclassified key
    params_export.py export [--version N ...] write config/flows/hunt/vNN.yaml (default: every
                                              version) and config/flows/hunt/index.yaml
    params_export.py check                    exit 1 when a committed config differs from a fresh
                                              export (or no longer resolves); versions without a
                                              committed config are listed, not failed

Offline: it imports hunt_flow for its PARAMS and sends nothing. The configs are committed (Batt
D4, 2026-10-21: config/flows/, committed): mob ids and our own numbers only.
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import Counter
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent))
import hunt_config as hcfg  # noqa: E402

INDEX = "index.yaml"
INDEX_HEADER = (
    "# GENERATED by scripts/params_export.py from scripts/hunt_flow.py PARAMS -- do not edit.\n"
    "# adopted: the adopted base (hunt_config.ADOPTED_VERSION; adoption is a commit moving it).\n"
    "# versions: each PARAMS version's hunt-block rule versions, engine id and the arm flags it\n"
    "# runs (odd k / odd blocks). rules: every rule version's numbers, as a person would pick it.\n"
)


def _params() -> dict[int, dict[str, Any]]:
    import hunt_flow as hf

    return hf.PARAMS


def index(params: dict[int, dict[str, Any]]) -> dict[str, Any]:
    versions: dict[int, Any] = {}
    rules: dict[str, dict[str, Any]] = {p: {} for p in hcfg.HUNT_PARAMS}
    for v in sorted(params):
        cfg = hcfg.export(params, v)
        row: dict[str, Any] = {p: cfg["hunt"][p]["rule"] for p in hcfg.HUNT_PARAMS}
        row["engine"] = cfg["engine"]["id"]
        row["map_zones"] = bool(cfg["map_node"].get("map_zones"))
        row["arms"] = [k for k, val in cfg["experiment"].items() if val is True]
        versions[v] = row
        for p in hcfg.HUNT_PARAMS:
            rules[p].setdefault(cfg["hunt"][p]["rule"], cfg["hunt"][p]["values"])
    return {"kind": "hunt-config-index", "format": hcfg.FORMAT,
            "adopted": hcfg.ADOPTED_VERSION, "versions": versions, "rules": rules}  # fmt: skip


def dump_index(data: dict[str, Any]) -> str:
    return INDEX_HEADER + hcfg.yaml_text(data)


def classify_cmd(params: dict[int, dict[str, Any]], version: int | None) -> int:
    first: dict[str, int] = {}
    for v in sorted(params):
        for k in params[v]:
            first.setdefault(k, v)
    keys = list(params[version]) if version is not None else list(first)
    rows, bad = [], []
    for k in keys:
        pat = hcfg.classify(k)
        if pat is None:
            bad.append(k)
            continue
        review = "REVIEW" if first[k] > hcfg.REVIEWED_THROUGH else ""
        rows.append((k, first[k], pat.cls, pat.param or "", review))
    for k, f, c, p, r in rows:
        print(f"{k:28s} v{f:<3d} {c:10s} {p:18s} {r}")
    counts = Counter(c for _, _, c, _, _ in rows)
    what = f"PARAMS[{version}]" if version is not None else f"all {len(params)} versions"
    print(json.dumps({"keys": what, "classified": len(rows), "total": len(keys),
                      "unclassified": bad, "classes": dict(sorted(counts.items())),
                      "review": [k for k, *_, r in rows if r]}))  # fmt: skip
    return 1 if bad else 0


def export_cmd(params: dict[int, dict[str, Any]], versions: list[int], root: Path) -> int:
    root.mkdir(parents=True, exist_ok=True)
    for v in versions:
        cfg = hcfg.export(params, v)
        if not hcfg.same(hcfg.resolve(cfg), params[v]):
            raise hcfg.ConfigError(f"v{v}: does not resolve back exactly")
        hcfg.path_for(v, root).write_text(hcfg.dump(cfg), encoding="utf-8")
    (root / INDEX).write_text(dump_index(index(params)), encoding="utf-8")
    print(json.dumps({"exported": versions, "root": str(root)}))
    return 0


def check_cmd(params: dict[int, dict[str, Any]], root: Path) -> int:
    stale, missing, broken = [], [], []
    for v in sorted(params):
        p = hcfg.path_for(v, root)
        if not p.exists():
            missing.append(v)
            continue
        if p.read_text(encoding="utf-8") != hcfg.dump(hcfg.export(params, v)):
            stale.append(v)
        try:
            if not hcfg.same(hcfg.resolve(hcfg.load(p)), params[v]):
                broken.append(v)
        except hcfg.ConfigError:
            broken.append(v)
    extra = sorted(int(p.stem[1:]) for p in root.glob("v*.yaml") if int(p.stem[1:]) not in params)
    idx = root / INDEX
    index_ok = idx.exists() and idx.read_text(encoding="utf-8") == dump_index(index(params))
    ok = not stale and not broken and not extra and index_ok
    print(json.dumps({"verdict": "PASS" if ok else "FAIL", "stale": stale, "broken": broken,
                      "unknown_files": extra, "index_current": index_ok,
                      "not_exported": missing}))  # fmt: skip
    return 0 if ok else 1


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)  # fmt: skip
    ap.add_argument("--root", type=Path, default=hcfg.CONFIG_DIR)
    sub = ap.add_subparsers(dest="cmd", required=True)
    cl = sub.add_parser("classify")
    cl.add_argument("--version", type=int)
    ex = sub.add_parser("export")
    ex.add_argument("--version", type=int, nargs="*")
    sub.add_parser("check")
    a = ap.parse_args()
    params = _params()
    if a.cmd == "classify":
        return classify_cmd(params, a.version)
    if a.cmd == "export":
        return export_cmd(params, a.version or sorted(params), a.root)
    return check_cmd(params, a.root)


if __name__ == "__main__":
    sys.exit(main())
