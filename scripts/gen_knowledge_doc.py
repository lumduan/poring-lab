#!/usr/bin/env python3
"""Generate docs/knowledge/README.md from the L1 concepts (packages/poring_skills, Batt 2026-10-07).

    gen_knowledge_doc.py [--check]

--check exits 1 when the committed doc differs from what the YAML generates (the drift test
runs it).
Never edit the doc by hand: edit packages/poring_skills/src/poring_skills/l1/*.yaml.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from poring_skills.schema import Concept, load_l1

DOC = Path(__file__).resolve().parents[1] / "docs" / "knowledge" / "README.md"
WAVES = {1: "1 Novice basics", 2: "2 combat", 3: "3 Merchant job change", 4: "4 Blacksmith"}


def render(concepts: dict[str, Concept]) -> str:
    out = [
        "<!-- GENERATED by scripts/gen_knowledge_doc.py from packages/poring_skills/src/"
        "poring_skills/l1/*.yaml: do not edit. -->",
        "",
        "# RO knowledge, layer 1: concepts",
        "",
        "What an action IS, in every RO client and server (Batt, 2026-10-07). How a client does it "
        "on screen (L2), where and with what on a server (L3) and its on-screen text (L4) are "
        "bindings, resolved per environment; a missing binding fails closed.",
        "",
        "| layer | contents | changes when |",
        "|---|---|---|",
        "| L1 concept | the action, steps in game terms, preconditions, failure modes, game rules, "
        "the outcome check | never (exceptions marked) |",
        "| L2 client | shortcuts, window anchors, layout, dialog vs window, packet versions | the "
        "client build |",
        "| L3 server | NPC positions, shops, warps, Kafra options, job-change scripts (generated "
        "locally, never committed when GPL) | the server |",
        "| L4 locale | on-screen text via the locale-pack keys (ADR-0011/0012) | the language |",
        "",
        "Every entry starts **unverified**: written from memory, which may mix renewal, "
        "pre-renewal and regional versions. It flips to **verified** only when its rule passes a "
        "pre-registered alone-test on RDP AND S2 (docs/demonstrations.md); `verified_on` then "
        "names the client build, server, locale, path and session. The runtime outcome is a "
        "SCREEN check (packets are never decision input, ADR-0007); the offline outcome is the "
        "packet verifier used for tests and labels.",
        "",
        f"{len(concepts)} concepts; "
        f"{sum(c.status == 'verified' for c in concepts.values())} verified.",
        "",
        "| id | purpose | workflow wave | status | runtime outcome (screen) |",
        "|---|---|---|---|---|",
    ]
    for cid, c in sorted(concepts.items()):
        wave = WAVES.get(c.workflow_wave or 0, "-")
        runtime = c.outcome.runtime.signal
        out.append(f"| `{cid}` | {c.purpose} | {wave} | {c.status} | {runtime} |")
    for cid, c in sorted(concepts.items()):
        out += ["", f"## `{cid}`", "", c.purpose, ""]
        if c.params:
            out.append(f"- **Parameters:** {', '.join(c.params)}")
        out.append(
            f"- **Status:** {c.status}"
            + (f" ({len(c.verified_on)} alone-test pass(es))" if c.verified_on else "")
        )
        out.append("- **Steps:**")
        out += [f"  {i}. {s}" for i, s in enumerate(c.steps, 1)]
        for label, items in (
            ("Preconditions", c.preconditions),
            ("Failure modes", c.failure_modes),
            ("Game rules", c.game_rules),
            ("Exceptions", c.exceptions),
        ):
            if items:
                out.append(f"- **{label}:**")
                out += [f"  - {x}" for x in items]
        rt = c.outcome.runtime
        out.append(f"- **Outcome, runtime ({rt.kind}):** {rt.signal}")
        off = c.outcome.offline
        out.append(
            f"- **Outcome, offline ({off.kind}):** {off.signal}"
            + (f" (`{off.verifier}`)" if off.verifier else "")
        )
        if c.bindings_needed:
            keys = ", ".join(f"`{b}`" for b in c.bindings_needed)
            out.append(f"- **Bindings needed:** {keys}")
        for v in c.verified_on:
            out.append(
                f"- **Verified on:** {v.client} / {v.server} / {v.locale} / {v.path}, "
                f"{v.rule}, session {v.session}, {v.date}"
            )
    return "\n".join(out) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = render(load_l1())
    if a.check:
        if not DOC.exists() or DOC.read_text() != text:
            print(f"{DOC} is stale: run scripts/gen_knowledge_doc.py", file=sys.stderr)
            return 1
        return 0
    DOC.parent.mkdir(parents=True, exist_ok=True)
    DOC.write_text(text)
    print(DOC)
    return 0


if __name__ == "__main__":
    sys.exit(main())
